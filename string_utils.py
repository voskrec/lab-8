def is_palindrome(s: str) -> bool:
    # База: строка из 1 символа или пустая — это палиндром
    if len(s) <= 1:
        return True
        
    # Если первый и последний символы не равны — это не палиндром
    if s[0] != s[-1]:
        return False
        
    # Шаг: отрезаем первый и последний символ и проверяем середину
    return is_palindrome(s[1:-1])


def is_anagram(s1: str, s2: str) -> bool:
    """Проверяет, являются ли две строки анаграммами."""
    # Убираем пробелы, приводим к нижнему регистру и сортируем буквы
    # Если отсортированные буквы совпадают — это анаграмма
    clean_s1 = "".join(sorted(s1.replace(" ", "").lower()))
    clean_s2 = "".join(sorted(s2.replace(" ", "").lower()))
    return clean_s1 == clean_s2


def count_words(text: str) -> int:
    """Считает количество слов в тексте."""
    # .split() без аргументов разбивает строку по любым пробельным символам (пробелы, переносы, табы)
    # и автоматически удаляет пустые элементы
    words = text.split()
    return len(words)